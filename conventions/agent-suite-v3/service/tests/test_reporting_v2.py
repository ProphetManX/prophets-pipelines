    def test_explicit_migration_is_idempotent_for_migrated_and_new_v2_databases(self):
        migrate = self.require_migration_api()
        migrate(self.database)
        before = self.snapshot()
        migrate(self.database)
        self.assertEqual(before, self.snapshot())
        self.database = self.root / "fresh-v2.sqlite3"
        Journal(self.database)
        before = self.snapshot()
