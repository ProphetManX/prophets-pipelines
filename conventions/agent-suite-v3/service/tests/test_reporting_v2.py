    def test_tool_schema_exposes_optional_metadata_and_no_worker_migration(self):
        listed = self.tool_request("tools/list")["tools"]
        schemas = {tool["name"]: tool["inputSchema"] for tool in listed}
        self.assertNotIn("journal_migrate", schemas)
        report = schemas["journal_report"]
        properties = report["properties"]
        self.assertIn("review_verdict", properties)
        self.assertNotIn("review_verdict", report["required"])
        verdict = properties["review_verdict"]
        branches = verdict.get("anyOf", verdict.get("oneOf", [verdict]))
        types = set()
        for branch in branches:
            value = branch.get("type", [])
            types.update([value] if isinstance(value, str) else value)
        self.assertTrue({"string", "null"} <= types)
        strings = next(branch for branch in branches if "string" in (
            [branch.get("type")] if isinstance(branch.get("type"), str) else branch.get("type", [])
        ))
        constraints = {**verdict, **strings}
        self.assertEqual(1, constraints.get("minLength"))
        self.assertEqual(160, constraints.get("maxLength"))
        item = properties["evidence"]["items"]
        self.assertIn("expected_outcome", item["properties"])
        self.assertIn("expectation_note", item["properties"])
        self.assertEqual({"pass", "red"}, set(item["properties"]["expected_outcome"]["enum"]))
        self.assertEqual("string", item["properties"]["expectation_note"]["type"])
        self.assertNotIn("expected_outcome", item["required"])
        self.assertNotIn("expectation_note", item["required"])

