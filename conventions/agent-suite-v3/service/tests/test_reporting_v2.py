    def test_red_requires_explicit_nonnegative_consistent_counters_and_actual_failure(self):
        cases = [
            ("no actual failure", PASS_COUNTERS),
            ("total exceeds executed", {**RED_COUNTERS, "total": "4"}),
            ("executed exceeds total", {**RED_COUNTERS, "total": "2"}),
            ("passed plus failed too small", {**RED_COUNTERS, "passed": "1"}),
            ("passed plus failed too large", {**RED_COUNTERS, "passed": "3"}),
            ("nonnumeric", {**RED_COUNTERS, "failed": "one"}),
        ]
        for name in RED_COUNTERS:
            cases.append((f"negative {name}", {**RED_COUNTERS, name: "-1"}))
            cases.append((f"missing {name}", {key: value for key, value in RED_COUNTERS.items() if key != name}))
        for description, counters in cases:
            with self.subTest(description=description):
                result = self.report([self.red(trx(counters))])
                self.assertTrue(result["gaps"])
                self.assertNotEqual(EXPECTED_RED, result["evidence"][0]["check_result"])

