# Hand-created historical schema, not generated by the implementation under test.
V1_SCHEMA = """
CREATE TABLE runs (
    run_id TEXT PRIMARY KEY, project_name TEXT NOT NULL, project_path TEXT NOT NULL,
    objective TEXT NOT NULL, requirements_ref TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE slices (
    run_id TEXT NOT NULL REFERENCES runs(run_id), slice_id TEXT NOT NULL,
    title TEXT NOT NULL, acceptance TEXT NOT NULL, required_evidence TEXT NOT NULL,
    created_at TEXT NOT NULL, PRIMARY KEY(run_id, slice_id)
);
CREATE TABLE invocations (
    invocation_id TEXT PRIMARY KEY, run_id TEXT NOT NULL, slice_id TEXT NOT NULL,
    role TEXT NOT NULL, started_at TEXT NOT NULL,
    FOREIGN KEY(run_id, slice_id) REFERENCES slices(run_id, slice_id)
);
CREATE TABLE events (
    event_id INTEGER PRIMARY KEY AUTOINCREMENT, run_id TEXT NOT NULL, slice_id TEXT NOT NULL,
    invocation_id TEXT NOT NULL, event_type TEXT NOT NULL, status TEXT NOT NULL,
    summary TEXT NOT NULL, gaps TEXT NOT NULL, created_at TEXT NOT NULL,
    counterparty_invocation_id TEXT,
    FOREIGN KEY(invocation_id) REFERENCES invocations(invocation_id),
    FOREIGN KEY(counterparty_invocation_id) REFERENCES invocations(invocation_id)
);
CREATE TABLE evidence (
    evidence_id INTEGER PRIMARY KEY AUTOINCREMENT,
    event_id INTEGER NOT NULL REFERENCES events(event_id), kind TEXT NOT NULL,
    uri TEXT NOT NULL, summary TEXT NOT NULL, check_result TEXT NOT NULL
);
CREATE INDEX events_run_order ON events(run_id, event_id);
CREATE INDEX events_invocation_order ON events(invocation_id, event_id);
PRAGMA user_version = 1;
"""


def trx(counters=None, outcome="Failed"):
    root = ET.Element("TestRun", xmlns="http://microsoft.com/schemas/VisualStudio/TeamTest/2010")
    summary = ET.SubElement(root, "ResultSummary", {} if outcome is None else {"outcome": outcome})
    ET.SubElement(summary, "Counters", RED_COUNTERS if counters is None else counters)
    return ET.tostring(root, encoding="unicode")


class IsolatedReportingFixture(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.project = self.root / "project"
        self.project.mkdir()
        self.database = self.root / "journal.sqlite3"

    def snapshot(self):
        """Logical schema/data snapshot, including IDs, strings and AUTOINCREMENT state."""
        with closing(sqlite3.connect(self.database)) as db:
            schema = db.execute(
                "SELECT type, name, tbl_name, sql FROM sqlite_master ORDER BY type, name"
            ).fetchall()
            rows = {}
            for name, in db.execute("SELECT name FROM sqlite_master WHERE type = 'table'"):
                quoted = '"' + name.replace('"', '""') + '"'
                rows[name] = db.execute(f"SELECT * FROM {quoted} ORDER BY rowid").fetchall()
            return db.execute("PRAGMA user_version").fetchone()[0], schema, rows

    def require_verdict_api(self):
        parameter = inspect.signature(Journal.report).parameters.get("review_verdict")
        if parameter is None:
            self.fail("Journal.report must accept optional review_verdict; the v1 API lacks it.")
        self.assertIsNot(inspect.Parameter.empty, parameter.default)

    def require_migration_api(self):
        migrate = getattr(Journal, "migrate", None)
        if not callable(migrate):
            self.fail("Journal.migrate(database) must explicitly migrate an isolated v1 database.")
        try:
            inspect.signature(migrate).bind(self.database)
        except TypeError:
            self.fail("Journal.migrate must be callable with the database path without an instance.")
        return migrate


class ReportingV2Tests(IsolatedReportingFixture):
    def setUp(self):
        super().setUp()
        self.journal = Journal(self.database)
        self.journal.register_run("run", "Reporting fixture", str(self.project), "Approved reporting v2")
        self.journal.register_slice("run", "slice", "Reporting", "Owner-approved contract")
        self.journal.start_invocation("run", "slice", "tests", "tests")
        self.journal.start_invocation("run", "slice", "reviewer", "review")
        self.journal.start_invocation("run", "slice", "lead", "lead")
        self.artifact_number = 0

    def artifact(self, body, kind="test_result", **metadata):
        self.artifact_number += 1
        name = f"artifact-{self.artifact_number}.txt"
        (self.project / name).write_text(body, encoding="utf-8")
        return {"kind": kind, "uri": name, "summary": "Isolated fixture.", **metadata}

    def red(self, body=None, note=RED_NOTE):
        return self.artifact(
            trx() if body is None else body, expected_outcome="red", expectation_note=note
        )

    def report(self, evidence=None, event_type="phase_changed", status="in_progress", **metadata):
        return self.journal.report(
            "tests", event_type, status, "Observed fixture behavior.", evidence, **metadata
        )

    def event(self, result):
        events = Journal(self.database).get_run("run")["events"]
        return next(event for event in events if event["event_id"] == result["event_id"])

    def assert_atomic_rejection(self, evidence=None, **metadata):
        before = self.snapshot()
        with self.assertRaises(JournalError):
            self.report(evidence, **metadata)
        self.assertEqual(before, self.snapshot(), "Rejected metadata must not append partial rows.")

    def assert_expected_red(self, result, note=RED_NOTE):
        self.assertTrue(result["recorded"])
        evidence = result["evidence"][0]
        self.assertEqual(EXPECTED_RED, evidence["check_result"])
        self.assertEqual("red", evidence.get("expected_outcome"))
        self.assertEqual(note, evidence.get("expectation_note"))
        self.assertEqual(result["evidence"], self.event(result)["evidence"])

    def tool_request(self, method, params=None, tools=None):
        return handle_request(
            {"jsonrpc": "2.0", "id": 1, "method": method, "params": params or {}},
            tools or JournalTools(self.journal),
        )["result"]

    def test_new_database_is_v2_with_additive_nullable_and_sql_default_fields(self):
        with closing(sqlite3.connect(self.database)) as db:
            self.assertEqual(2, db.execute("PRAGMA user_version").fetchone()[0])
            for table, fields in (
                ("events", {"review_verdict"}),
                ("evidence", {"expected_outcome", "expectation_note"}),
            ):
                self.assertTrue(fields <= {row[1] for row in db.execute(f"PRAGMA table_info({table})")})
            # Omit new columns exactly as historical SQL writers did.
            with db:
                event_id = db.execute(
                    """INSERT INTO events
                       (run_id, slice_id, invocation_id, event_type, status, summary, gaps, created_at)
                       VALUES ('run', 'slice', 'tests', 'note', 'in_progress', 'Legacy', '[]', 'then')"""
                ).lastrowid
                db.execute(
                    """INSERT INTO evidence (event_id, kind, uri, summary, check_result)
                       VALUES (?, 'other', 'fixture', 'Legacy', 'reference_only')""", (event_id,)
                )
            self.assertEqual((None,), db.execute(
                "SELECT review_verdict FROM events WHERE event_id = ?", (event_id,)
            ).fetchone())
            self.assertEqual(("pass", ""), db.execute(
                "SELECT expected_outcome, expectation_note FROM evidence WHERE event_id = ?", (event_id,)
            ).fetchone())

    def test_review_verdict_is_free_text_separate_from_status_including_lead_relays(self):
        self.require_verdict_api()
        for worker in ("reviewer", "lead"):
            for verdict in ("Needs a domain specialist; not an approval", "\u5ba1" * 160):
                with self.subTest(worker=worker, verdict_length=len(verdict)):
                    result = self.journal.report(
                        worker, "review_returned", "awaiting_review", "Review relayed.",
                        review_verdict=verdict,
                    )
                    self.assertEqual("awaiting_review", result["status"])
                    self.assertEqual(verdict, result.get("review_verdict"))
                    event = self.event(result)
                    self.assertEqual(verdict, event.get("review_verdict"))
                    self.assertEqual("awaiting_review", event["status"])
                    with closing(sqlite3.connect(self.database)) as db:
                        self.assertEqual((verdict,), db.execute(
                            "SELECT review_verdict FROM events WHERE event_id = ?", (result["event_id"],)
                        ).fetchone())

